// ── Knowledge: Epistemic state ────────────────────────────────────────────────

// UpsertEpistemicState inserts or replaces the epistemic state blob for a book.
func UpsertEpistemicState(db *sql.DB, id, bookID, dataJSON string, version int) error {
	_, err := db.Exec(
		`INSERT INTO epistemic_states(id, book_id, version, data)
		 VALUES (?, ?, ?, ?)
		 ON CONFLICT(book_id) DO UPDATE SET
		   version = excluded.version,
		   data = excluded.data,
		   updated_at = CURRENT_TIMESTAMP`,
		id, bookID, version, dataJSON,
	)
	return err
}

// GetEpistemicState returns the epistemic state for a book.
func GetEpistemicState(db *sql.DB, bookID string) (id, dataJSON string, version int, err error) {
	row := db.QueryRow(
		`SELECT id, data, version FROM epistemic_states WHERE book_id = ?`, bookID,
	)
	err = row.Scan(&id, &dataJSON, &version)
	if err == sql.ErrNoRows {
		err = nil
	}
	return
}

// ── Stage progress ────────────────────────────────────────────────────────────

// MarkStageComplete records that stage stageName completed for jobID.
// Idempotent — safe to call multiple times for the same (job, stage) pair.
func MarkStageComplete(db *sql.DB, jobID, stageName string) error {
	_, err := db.Exec(
		`INSERT OR IGNORE INTO stage_progress(job_id, stage_name) VALUES (?, ?)`,
		jobID, stageName,
	)
	return err
}

// CompletedStages returns the set of stage names that have been completed for jobID.
// Returns an empty map (not nil) when the job has no completed stages.
func CompletedStages(db *sql.DB, jobID string) (map[string]bool, error) {
	rows, err := db.Query(
		`SELECT stage_name FROM stage_progress WHERE job_id = ?`, jobID,
	)
	if err != nil {
		return nil, err
	}
	defer func() { _ = rows.Close() }()

	result := make(map[string]bool)
	for rows.Next() {
		var name string
		if err := rows.Scan(&name); err != nil {
			return nil, err
		}
		result[name] = true
	}
	return result, rows.Err()
}

// scanner is implemented by both *sql.Row and *sql.Rows.
type scanner interface {
	Scan(dest ...any) error
}

func scanJob(s scanner) (*Job, error) {
	var j Job
	var result, errStr sql.NullString
	var startedAt, finishedAt sql.NullTime
	if err := s.Scan(
		&j.ID, &j.Type, &j.BookDir, &j.ChapterNum, &j.Payload,
		&j.Status, &j.Priority, &j.Batch,
		&result, &errStr, &j.Attempt, &j.MaxAttempts,
		&j.CreatedAt, &startedAt, &finishedAt,
	); err != nil {
		return nil, err
	}
	if result.Valid {
		j.Result = result.String
	}
	if errStr.Valid {
		j.Error = errStr.String
	}
	if startedAt.Valid {
		t := startedAt.Time
		j.StartedAt = &t
	}
	if finishedAt.Valid {
		t := finishedAt.Time
		j.FinishedAt = &t
	}
	return &j, nil
}
