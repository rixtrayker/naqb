// ClaimRow mirrors the claims table for CRUD operations.
type ClaimRow struct {
	ID          string
	BookID      string
	Chapter     int
	Paragraph   int
	SentenceIdx int
	Text        string
	ClaimType   string
	Confidence  float64
	Language    string
	CreatedAt   time.Time
}

// InsertClaim inserts a new claim row.
func InsertClaim(db *sql.DB, c ClaimRow) error {
	_, err := db.Exec(
		`INSERT INTO claims(id, book_id, chapter, paragraph, sentence_idx, text, claim_type, confidence, language)
		 VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)`,
		c.ID, c.BookID, c.Chapter, c.Paragraph, c.SentenceIdx, c.Text, c.ClaimType, c.Confidence, c.Language,
	)
	return err
}

// GetClaim retrieves a claim by ID.
func GetClaim(db *sql.DB, id string) (*ClaimRow, error) {
	row := db.QueryRow(
		`SELECT id, book_id, chapter, paragraph, sentence_idx, text, claim_type, confidence, language, created_at
		 FROM claims WHERE id = ?`, id,
	)
	var c ClaimRow
	if err := row.Scan(&c.ID, &c.BookID, &c.Chapter, &c.Paragraph, &c.SentenceIdx,
		&c.Text, &c.ClaimType, &c.Confidence, &c.Language, &c.CreatedAt); err != nil {
		if err == sql.ErrNoRows {
			return nil, nil
		}
		return nil, err
	}
	return &c, nil
}

// ListClaims returns all claims for a book, optionally filtered by chapter (0 = all).
func ListClaims(db *sql.DB, bookID string, chapter int) ([]ClaimRow, error) {
	var (
		rows *sql.Rows
		err  error
	)
	if chapter == 0 {
		rows, err = db.Query(
			`SELECT id, book_id, chapter, paragraph, sentence_idx, text, claim_type, confidence, language, created_at
			 FROM claims WHERE book_id = ? ORDER BY chapter, paragraph, sentence_idx`,
			bookID,
		)
	} else {
		rows, err = db.Query(
			`SELECT id, book_id, chapter, paragraph, sentence_idx, text, claim_type, confidence, language, created_at
			 FROM claims WHERE book_id = ? AND chapter = ? ORDER BY paragraph, sentence_idx`,
			bookID, chapter,
		)
	}
	if err != nil {
		return nil, err
	}
	defer func() { _ = rows.Close() }()
	return scanClaims(rows)
}

// DeleteClaim removes a claim and its relations.
func DeleteClaim(db *sql.DB, id string) error {
	_, err := db.Exec(`DELETE FROM claims WHERE id = ?`, id)
	return err
}

func scanClaims(rows *sql.Rows) ([]ClaimRow, error) {
	var claims []ClaimRow
	for rows.Next() {
		var c ClaimRow
		if err := rows.Scan(&c.ID, &c.BookID, &c.Chapter, &c.Paragraph, &c.SentenceIdx,
			&c.Text, &c.ClaimType, &c.Confidence, &c.Language, &c.CreatedAt); err != nil {
			return nil, err
		}
		claims = append(claims, c)
	}
	return claims, rows.Err()
}

