// ── Jobs ──────────────────────────────────────────────────────────────────────

// EnqueueJob inserts a new job and returns its ID.
// id should be a UUID generated by the caller.
// payload is any JSON-serialisable value.
func EnqueueJob(db *sql.DB, id, jobType, bookDir string, chapterNum int, payload any, batch bool, priority int) error {
	payloadJSON, err := json.Marshal(payload)
	if err != nil {
		return fmt.Errorf("enqueue: marshal payload: %w", err)
	}
	_, err = db.Exec(
		`INSERT INTO jobs(id, type, book_dir, chapter_num, payload, batch, priority)
		 VALUES (?, ?, ?, ?, ?, ?, ?)`,
		id, jobType, bookDir, chapterNum, string(payloadJSON), batch, priority,
	)
	return err
}

// DequeueJob atomically claims the highest-priority pending job, setting its
// status to "running". Returns nil if the queue is empty.
func DequeueJob(db *sql.DB) (*Job, error) {
	tx, err := db.Begin()
	if err != nil {
		return nil, err
	}
	defer tx.Rollback() //nolint:errcheck

	row := tx.QueryRow(
		`SELECT id FROM jobs WHERE status = 'pending'
		 ORDER BY priority DESC, created_at ASC LIMIT 1`,
	)
	var jobID string
	if err := row.Scan(&jobID); err != nil {
		if err == sql.ErrNoRows {
			return nil, nil
		}
		return nil, err
	}

	if _, err := tx.Exec(
		`UPDATE jobs SET status = 'running', started_at = CURRENT_TIMESTAMP,
		                 attempt = attempt + 1 WHERE id = ?`, jobID,
	); err != nil {
		return nil, err
	}
	if err := tx.Commit(); err != nil {
		return nil, err
	}

	return GetJob(db, jobID)
}

// UpdateJobStatus updates the status, result, and error fields of a job.
// On terminal states (done/failed/cancelled) it also sets finished_at.
func UpdateJobStatus(db *sql.DB, id, status, result, errMsg string) error {
	switch status {
	case "done", "failed", "cancelled":
		_, err := db.Exec(
			`UPDATE jobs SET status = ?, result = ?, error = ?,
			                 finished_at = CURRENT_TIMESTAMP WHERE id = ?`,
			status, result, errMsg, id,
		)
		return err
	default:
		_, err := db.Exec(
			`UPDATE jobs SET status = ?, result = ?, error = ? WHERE id = ?`,
			status, result, errMsg, id,
		)
		return err
	}
}

// GetJob returns a job by ID.
func GetJob(db *sql.DB, id string) (*Job, error) {
	row := db.QueryRow(
		`SELECT id, type, book_dir, chapter_num, payload, status, priority, batch,
		        result, error, attempt, max_attempts, created_at, started_at, finished_at
		 FROM jobs WHERE id = ?`, id,
	)
	return scanJob(row)
}

// ListJobs returns jobs filtered by status ("" = all statuses), ordered by
// priority DESC then creation time ASC.
func ListJobs(db *sql.DB, status string, limit int) ([]Job, error) {
	if limit <= 0 {
		limit = 50
	}

	var (
		rows *sql.Rows
		err  error
	)
	if status == "" {
		rows, err = db.Query(
			`SELECT id, type, book_dir, chapter_num, payload, status, priority, batch,
			        result, error, attempt, max_attempts, created_at, started_at, finished_at
			 FROM jobs ORDER BY priority DESC, created_at ASC LIMIT ?`, limit,
		)
	} else {
		rows, err = db.Query(
			`SELECT id, type, book_dir, chapter_num, payload, status, priority, batch,
			        result, error, attempt, max_attempts, created_at, started_at, finished_at
			 FROM jobs WHERE status = ?
			 ORDER BY priority DESC, created_at ASC LIMIT ?`, status, limit,
		)
	}
	if err != nil {
		return nil, err
	}
	defer func() { _ = rows.Close() }()

	var jobs []Job
	for rows.Next() {
		j, err := scanJob(rows)
		if err != nil {
			return nil, err
		}
		jobs = append(jobs, *j)
	}
	return jobs, rows.Err()
}

// CancelJob sets a pending or running job to "cancelled".
func CancelJob(db *sql.DB, id string) error {
	_, err := db.Exec(
		`UPDATE jobs SET status = 'cancelled', finished_at = CURRENT_TIMESTAMP
		 WHERE id = ? AND status IN ('pending','running')`, id,
	)
	return err
}

