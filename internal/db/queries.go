// ── Types ─────────────────────────────────────────────────────────────────────

// Session represents a persisted chat/agent session.
type Session struct {
	ID         string
	BookDir    string
	ChapterNum int
	CreatedAt  time.Time
	UpdatedAt  time.Time
}

// Message represents a single message within a session.
type Message struct {
	ID        string
	SessionID string
	Role      string // "user", "assistant", or "tool"
	Content   string
	TokensIn  int
	TokensOut int
	Model     string
	CreatedAt time.Time
}

// Job represents a queued background job.
type Job struct {
	ID          string
	Type        string
	BookDir     string
	ChapterNum  int
	Payload     string // raw JSON
	Status      string // pending|running|done|failed|cancelled
	Priority    int
	Batch       bool
	Result      string // JSON on success
	Error       string // message on failure
	Attempt     int
	MaxAttempts int
	CreatedAt   time.Time
	StartedAt   *time.Time
	FinishedAt  *time.Time
}

// ── Sessions ──────────────────────────────────────────────────────────────────

// CreateSession inserts a new session row and returns its ID.
// The ID is a UUID generated by the caller (pass from uuid.NewString()).
func CreateSession(db *sql.DB, id, bookDir string, chapterNum int) error {
	_, err := db.Exec(
		`INSERT INTO sessions(id, book_dir, chapter_num) VALUES (?, ?, ?)`,
		id, bookDir, chapterNum,
	)
	return err
}

// GetSession returns a session by ID.
func GetSession(db *sql.DB, id string) (*Session, error) {
	row := db.QueryRow(
		`SELECT id, book_dir, chapter_num, created_at, updated_at FROM sessions WHERE id = ?`, id,
	)
	var s Session
	if err := row.Scan(&s.ID, &s.BookDir, &s.ChapterNum, &s.CreatedAt, &s.UpdatedAt); err != nil {
		if err == sql.ErrNoRows {
			return nil, fmt.Errorf("session %s not found", id)
		}
		return nil, err
	}
	return &s, nil
}

// ListSessions returns sessions for a book directory, ordered by most recent first.
func ListSessions(db *sql.DB, bookDir string, limit int) ([]Session, error) {
	if limit <= 0 {
		limit = 20
	}
	rows, err := db.Query(
		`SELECT id, book_dir, chapter_num, created_at, updated_at
		 FROM sessions WHERE book_dir = ?
		 ORDER BY created_at DESC LIMIT ?`,
		bookDir, limit,
	)
	if err != nil {
		return nil, err
	}
	defer func() { _ = rows.Close() }()

	var sessions []Session
	for rows.Next() {
		var s Session
		if err := rows.Scan(&s.ID, &s.BookDir, &s.ChapterNum, &s.CreatedAt, &s.UpdatedAt); err != nil {
			return nil, err
		}
		sessions = append(sessions, s)
	}
	return sessions, rows.Err()
}

// TouchSession updates the updated_at timestamp on a session.
func TouchSession(db *sql.DB, id string) error {
	_, err := db.Exec(`UPDATE sessions SET updated_at = CURRENT_TIMESTAMP WHERE id = ?`, id)
	return err
}

// DeleteSession removes a session and its messages (cascade).
func DeleteSession(db *sql.DB, id string) error {
	_, err := db.Exec(`DELETE FROM sessions WHERE id = ?`, id)
	return err
}

